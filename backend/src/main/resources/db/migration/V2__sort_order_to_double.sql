-- V2：並び順（sort_order）を、整数から小数に変える
-- 検索・絞り込み中でも並び替えられるようにするため（要件定義書 5.2 No.16）
-- カードを動かしたときは、そのカードの番号だけを「上のカードとすぐ下のカードの真ん中」（例：0 と 1 の間なら 0.5）に変える
-- ほかのカードの番号には触らないので、画面に見えていないカードの順番もずれない

-- 今入っている整数（0, 1, 2…）は、そのまま小数（0.0, 1.0, 2.0…）になる。インデックスもそのまま使える
ALTER TABLE tasks ALTER COLUMN sort_order TYPE DOUBLE PRECISION;
